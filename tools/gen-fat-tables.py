"""Generate pinned FAT name tables from UnicodeData 17.0.0 and CP437 2.00."""
import hashlib
import pathlib
import sys

unicode_path, cp_path, output_path, case_path = map(pathlib.Path, sys.argv[1:])
expected_unicode = '2e1efc1dcb59c575eedf5ccae60f95229f706ee6d031835247d843c11d96470c'
expected_cp437 = '6bad4dabcdf5940227c7d81fab130dcb18a77850b5d79de28b5dc4e047b0aaac'
for path, expected in [(unicode_path, expected_unicode), (cp_path, expected_cp437)]:
    if hashlib.sha256(path.read_bytes()).hexdigest() != expected:
        raise SystemExit('Unexpected source hash for ' + str(path))

upper, lower = {}, {}
for line in unicode_path.read_text().splitlines():
    fields = line.split(';')
    scalar = int(fields[0], 16)
    if fields[12]:
        upper[scalar] = int(fields[12], 16)
    if fields[13]:
        lower[scalar] = int(fields[13], 16)
cp = {}
for line in cp_path.read_text().splitlines():
    if line == '\x1a':  # DOS end-of-file marker in the source mapping.
        continue
    fields = line.split('#')[0].split()
    if fields:
        cp[int(fields[0], 16)] = int(fields[1], 16)
assert len(cp) == 256
lines = ['/* SPDX-License-Identifier: Unicode-3.0',
         ' * Copyright (c) 1991-2026 Unicode, Inc.',
         ' * Generated by tools/gen-fat-tables.py. See third-party/Unicode-LICENSE.txt.',
         ' * UnicodeData 17.0.0; CP437 mapping version 2.00.',
         ' * UnicodeData SHA256: ' + hashlib.sha256(unicode_path.read_bytes()).hexdigest(),
         ' * CP437 SHA256: ' + hashlib.sha256(cp_path.read_bytes()).hexdigest(),
         ' */', '']
for name, values in [('fat_cp437', [cp[i] for i in range(256)]),
                     ('fat_cp437_lower', [lower.get(cp[i], cp[i]) for i in range(256)])]:
    lines.append('static const uint16_t ' + name + '[256] = {')
    for i in range(0, 256, 8):
        lines.append('\t' + ', '.join('0x%04x' % v for v in values[i:i+8]) + ',')
    lines.extend(['};', ''])
output_path.write_text('\n'.join(lines).rstrip() + '\n', encoding='ascii')
lines = lines[:8]
lines.append('static const fsimg_case_pair_t fsimg_upper[] = {')
for scalar, mapped in sorted(upper.items()):
    lines.append('\t{ 0x%06x, 0x%06x },' % (scalar, mapped))
lines.extend(['};', ''])
case_path.write_text('\n'.join(lines), encoding='ascii')
