# Generate pinned FAT name tables from UnicodeData 17.0.0 and CP437 2.00.
require "digest"

module FatTables
  module_function

  def generate(unicode_path:, cp_path:, output_path:, case_path:)
    sources = [
      [unicode_path, "2e1efc1dcb59c575eedf5ccae60f95229f706ee6d031835247d843c11d96470c"],
      [cp_path, "6bad4dabcdf5940227c7d81fab130dcb18a77850b5d79de28b5dc4e047b0aaac"]
    ].map do |path, expected|
      bytes = File.binread(path)
      abort("Unexpected source hash for #{path}") unless Digest::SHA256.hexdigest(bytes) == expected
      bytes
    end

    upper, lower = mappings(sources.first)
    cp = codepage(sources.last)
    preamble = [
      "/* SPDX-License-Identifier: Unicode-3.0",
      " * Copyright (c) 1991-2026 Unicode, Inc.",
      " * Generated by tools/gen-fat-tables.rb. See third-party/Unicode-LICENSE.txt.",
      " * UnicodeData 17.0.0; CP437 mapping version 2.00.",
      " * UnicodeData SHA256: #{Digest::SHA256.hexdigest(sources.first)}",
      " * CP437 SHA256: #{Digest::SHA256.hexdigest(sources.last)}",
      " */",
      ""
    ]
    names = [["fat_cp437", cp], ["fat_cp437_lower", cp.map { lower.fetch(_1, _1) }]]
    tables = names.flat_map do |name, values|
      [
        "static const uint16_t #{name}[256] = {",
        *values.each_slice(8).map { "\t#{_1.map { |value| format("0x%04x", value) }.join(", ")}," },
        "};",
        ""
      ]
    end

    File.write(output_path, (preamble + tables).join("\n").rstrip + "\n")
    pairs = upper.sort.map { |scalar, mapped| format("\t{ 0x%06x, 0x%06x },", scalar, mapped) }
    File.write(
      case_path,
      [
        *preamble,
        "static const fsimg_case_pair_t fsimg_upper[] = {",
        *pairs,
        "};",
        ""
      ].join("\n")
    )
  end

  def mappings(text)
    text.lines.each_with_object([{}, {}]) do |line, (upper, lower)|
      fields = line.chomp.split(";", -1)
      scalar = fields[0].to_i(16)
      upper[scalar] = fields[12].to_i(16) unless fields[12].empty?
      lower[scalar] = fields[13].to_i(16) unless fields[13].empty?
    end
  end

  def codepage(text)
    mapping = text
      .lines
      .filter_map do |line|
        next if line.chomp == "\x1a"
        fields = line.split("#", 2).first.to_s.split
        next if fields.empty?
        fields.first(2).map { Integer(_1, 16) }
      end
      .to_h
    abort("CP437 must define 256 bytes") unless mapping.size == 256
    (0...256).map { mapping.fetch(_1) }
  end
end

abort("usage: gen-fat-tables.rb UnicodeData.txt CP437.TXT name-tables.h case-tables.h") unless ARGV.size == 4
FatTables.generate(
  unicode_path: ARGV[0],
  cp_path: ARGV[1],
  output_path: ARGV[2],
  case_path: ARGV[3]
)
