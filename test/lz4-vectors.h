/* Raw LZ4 blocks made once by the reference command, lz4 v1.11.0:
 *
 *	lz4 -l -c -q < INPUT > OUTPUT
 *
 * The legacy frame is the bytes 02 21 4c 18, then for each block its
 * length as four little-endian bytes and the block. Each input here fits
 * one block, so the first eight bytes of OUTPUT were dropped and the rest
 * is the array below. Every block was checked to decode back to its input
 * with lz4 -d. The recipes below regenerate each input without an encoder
 * or an external tool:
 *
 *   ZEROS    all zero bytes.
 *   TEXT     the first decoded bytes of lz4_text.
 *   PATTERN  the seven bytes "abcdefg" repeated.
 *   TILE     a 300-byte tile repeated; its bytes are the low bytes of
 *            xorshift32 from seed 0x12345678 (shifts 13 left, 17 right,
 *            5 left).
 *   RANDOM   the same generator from seed 0x2468ace1, the bytes
 *            incompressible, so the block is one literal run.
 */
typedef enum lz4_recipe {
	LZ4_ZEROS, LZ4_TEXT, LZ4_PATTERN, LZ4_TILE, LZ4_RANDOM
} lz4_recipe_t;

#define LZ4_TILE_BYTES	300u

