/* Every vector repeats this byte pattern with its table-specified period. */
static inline uint8_t
lzfse_plain_byte(const lzfse_vector_t *vector, size_t offset)
{
	return ((uint8_t)(33 + (7 * (offset % vector->plain_period)) % 61));
}

